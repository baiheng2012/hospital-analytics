USE HospitalDW;
GO

-- 为什么全部用 NVARCHAR?
-- staging 层只负责"原样收货",不做类型转换。
-- 如果日期列里有一个脏值,用 DATETIME 类型整个导入会失败;用文本则一定能进来。
-- 类型转换留到 dw 层,并且在那里处理错误。

DROP TABLE IF EXISTS stg.patients;
CREATE TABLE stg.patients (
    Id NVARCHAR(50), BIRTHDATE NVARCHAR(50), DEATHDATE NVARCHAR(50),
    SSN NVARCHAR(50), DRIVERS NVARCHAR(50), PASSPORT NVARCHAR(50),
    PREFIX NVARCHAR(50), FIRST NVARCHAR(100), MIDDLE NVARCHAR(100),
    LAST NVARCHAR(100), SUFFIX NVARCHAR(50), MAIDEN NVARCHAR(100),
    MARITAL NVARCHAR(50), RACE NVARCHAR(50), ETHNICITY NVARCHAR(50),
    GENDER NVARCHAR(50), BIRTHPLACE NVARCHAR(200), ADDRESS NVARCHAR(200),
    CITY NVARCHAR(100), STATE NVARCHAR(100), COUNTY NVARCHAR(100),
    FIPS NVARCHAR(50), ZIP NVARCHAR(50), LAT NVARCHAR(50), LON NVARCHAR(50),
    HEALTHCARE_EXPENSES NVARCHAR(50), HEALTHCARE_COVERAGE NVARCHAR(50),
    INCOME NVARCHAR(50)
);

DROP TABLE IF EXISTS stg.encounters;
CREATE TABLE stg.encounters (
    Id NVARCHAR(50), START NVARCHAR(50), STOP NVARCHAR(50),
    PATIENT NVARCHAR(50), ORGANIZATION NVARCHAR(50), PROVIDER NVARCHAR(50),
    PAYER NVARCHAR(50), ENCOUNTERCLASS NVARCHAR(50), CODE NVARCHAR(50),
    DESCRIPTION NVARCHAR(500), BASE_ENCOUNTER_COST NVARCHAR(50),
    TOTAL_CLAIM_COST NVARCHAR(50), PAYER_COVERAGE NVARCHAR(50),
    REASONCODE NVARCHAR(50), REASONDESCRIPTION NVARCHAR(500)
);

DROP TABLE IF EXISTS stg.organizations;
CREATE TABLE stg.organizations (
    Id NVARCHAR(50), NAME NVARCHAR(300), ADDRESS NVARCHAR(300),
    CITY NVARCHAR(100), STATE NVARCHAR(50), ZIP NVARCHAR(50),
    LAT NVARCHAR(50), LON NVARCHAR(50), PHONE NVARCHAR(200),
    REVENUE NVARCHAR(50), UTILIZATION NVARCHAR(50), NPI NVARCHAR(50)
);

DROP TABLE IF EXISTS stg.providers;
CREATE TABLE stg.providers (
    Id NVARCHAR(50), ORGANIZATION NVARCHAR(50), NAME NVARCHAR(200),
    GENDER NVARCHAR(50), SPECIALITY NVARCHAR(200), ADDRESS NVARCHAR(300),
    CITY NVARCHAR(100), STATE NVARCHAR(50), ZIP NVARCHAR(50),
    LAT NVARCHAR(50), LON NVARCHAR(50), ENCOUNTERS NVARCHAR(50),
    PROCEDURES NVARCHAR(50), NPI NVARCHAR(50)
);
GO